FONT = 'C:/Windows/Fonts/times.ttf'

def canvas(height=1100):
    im = Image.new('RGB', (1600, height), 'white')
    d = ImageDraw.Draw(im)
    def text(x, y, s, size=35):
        d.multiline_text((x,y), s, fill='black', font=ImageFont.truetype(FONT,size), anchor='mm', align='center', spacing=9)
    def box(x,y,w,h,s):
        d.rounded_rectangle((x-w/2,y-h/2,x+w/2,y+h/2),radius=20,outline='black',width=3)
        text(x,y,s)
    def arrow(points,label='',pos=None):
        d.line(points,fill='black',width=3)
        x,y=points[-1];px,py=points[-2];a=math.atan2(y-py,x-px)
        d.polygon([(x,y),(x-19*math.cos(a-.45),y-19*math.sin(a-.45)),(x-19*math.cos(a+.45),y-19*math.sin(a+.45))],fill='black')
        if label: text(*pos,label,29)
    return im,text,box,arrow

